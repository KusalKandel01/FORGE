import { Lock, ScrollText } from "lucide-react";
import Link from "next/link";

interface Section {
  heading: string;
  body: string[];
}

function LegalPage({
  kind,
  title,
  intro,
  sections,
}: {
  kind: "terms" | "privacy";
  title: string;
  intro: string;
  sections: Section[];
}) {
  const updated = new Date().toLocaleDateString("en-US", {
    month: "long",
    year: "numeric",
  });
  return (
    <div className="mx-auto w-full max-w-3xl px-4 py-12">
      <div className="mb-8 flex items-center gap-3">
        <span className="flex h-10 w-10 items-center justify-center bg-volt text-black">
          {kind === "terms" ? (
            <ScrollText className="h-5 w-5" aria-hidden />
          ) : (
            <Lock className="h-5 w-5" aria-hidden />
          )}
        </span>
        <div>
          <h1 className="font-display text-4xl tracking-wide md:text-5xl">
            {title}
          </h1>
          <p className="text-xs uppercase tracking-widest text-muted-foreground">
            Last updated: {updated}
          </p>
        </div>
      </div>

      <p className="mb-10 border-l-2 border-volt pl-4 leading-relaxed text-muted-foreground">
        {intro}
      </p>

      <div className="space-y-8">
        {sections.map((section, i) => (
          <section key={section.heading}>
            <h2 className="mb-3 flex items-baseline gap-3 font-head text-sm font-extrabold uppercase tracking-[0.18em]">
              <span className="text-volt">{String(i + 1).padStart(2, "0")}</span>
              {section.heading}
            </h2>
            <div className="space-y-3 text-sm leading-relaxed text-muted-foreground">
              {section.body.map((p, j) => (
                <p key={j}>{p}</p>
              ))}
            </div>
          </section>
        ))}
      </div>

      <div className="mt-12 border-t border-border pt-6 text-sm text-muted-foreground">
        <Link
          href="#/"
          className="font-head text-xs font-extrabold uppercase tracking-[0.2em] text-volt hover:underline"
        >
          Back to home
        </Link>
      </div>
    </div>
  );
}

